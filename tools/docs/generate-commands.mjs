#!/usr/bin/env node
// Generates one documentation page per command from oclif.manifest.json, itself built from messages/*.md: --help, the
// README and the website share one source. Run `npm run docs:commands` from the repository root.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const manifestPath = path.join(root, 'oclif.manifest.json');
const outputDir = path.join(root, 'website/docs/commands');
const repoUrl = 'https://github.com/benahm/sf-df';

// Sidebar order: the delivery workflow first, then the standalone tools.
const ORDER = [
  'df:deploy',
  'df:org:map',
  'df:git:delta',
  'df:git:merge-driver:install',
  'df:git:merge-driver:run',
  'df:git:merge-driver:uninstall',
  'df:profile:retrieve',
  'df:profile:to-permset',
  'df:org:align',
];
const GLOBAL_FLAGS = new Set(['json', 'flags-dir']);

if (!existsSync(manifestPath)) {
  console.error('oclif.manifest.json not found: run `npm run docs:commands` from the repository root.');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const commandLine = (id) => `sf ${id.replaceAll(':', ' ')}`;
const slugOf = (id) => id.replaceAll(':', '-');
const schemaOf = (id) => `${id.replaceAll('-', '__').replaceAll(':', '-')}.json`;

// The pages are CommonMark (.md): outside code spans, "<Class>Test" would be read as an HTML tag.
const escapeProse = (text) =>
  text
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith('`') ? part : part.replaceAll('<', '&lt;').replaceAll('>', '&gt;')))
    .join('');

const renderExample = (id, example) => {
  const raw = typeof example === 'string' ? example : example.command;
  const text = raw.replaceAll('<%= config.bin %>', 'sf').replaceAll('<%= command.id %>', id.replaceAll(':', ' '));
  const lines = text.split('\n');
  const commandIndex = lines.findIndex((line) => line.trim().startsWith('sf '));
  const intro = lines.slice(0, Math.max(commandIndex, 0)).join(' ').trim();
  const commands = lines.slice(commandIndex === -1 ? 0 : commandIndex).map((line) => line.trim());
  return [intro ? escapeProse(intro) : undefined, '```bash', ...commands, '```'].filter((line) => line !== undefined).join('\n');
};

const flagTitle = (flag) => {
  const names = [`--${flag.name}`, ...(flag.char ? [`-${flag.char}`] : [])];
  return names.map((name) => `\`${name}\``).join(', ');
};

const renderFlag = (flag) => {
  const lines = [`### ${flagTitle(flag)}`, ''];
  if (flag.summary) {
    lines.push(escapeProse(flag.summary), '');
  }

  if (flag.description) {
    lines.push(escapeProse(flag.description), '');
  }

  const facts = [];
  if (flag.required) {
    facts.push('**Required.**');
  }

  if (flag.options?.length) {
    facts.push(`Values: ${flag.options.map((option) => `\`${option}\``).join(', ')}.`);
  }

  if (flag.default !== undefined && flag.default !== false) {
    facts.push(`Default: \`${flag.default}\`.`);
  }

  if (flag.aliases?.length) {
    facts.push(`Deprecated alias: ${flag.aliases.map((alias) => `\`--${alias}\``).join(', ')}.`);
  }

  if (facts.length > 0) {
    lines.push(facts.join(' '), '');
  }

  return lines.join('\n');
};

const usageOf = (id, flags) => {
  const parts = flags.map((flag) => {
    const value = flag.type === 'boolean' ? '' : ' <value>';
    return flag.required ? `--${flag.name}${value}` : `[--${flag.name}${value}]`;
  });
  return `${commandLine(id)} ${parts.join(' ')}`.trim();
};

const renderCommand = (id, command, position) => {
  const flags = Object.values(command.flags)
    .filter((flag) => !flag.hidden && !GLOBAL_FLAGS.has(flag.name))
    .sort((a, b) => Number(Boolean(b.required)) - Number(Boolean(a.required)));
  const source = `src/commands/${id.split(':').slice(1).join('/')}.ts`;

  return [
    '---',
    `title: ${JSON.stringify(commandLine(id))}`,
    `sidebar_label: ${JSON.stringify(commandLine(id).replace(/^sf df /, ''))}`,
    `sidebar_position: ${position}`,
    `description: ${JSON.stringify(command.summary ?? '')}`,
    `custom_edit_url: ${repoUrl}/blob/main/messages/${id.replaceAll(':', '.')}.md`,
    '---',
    '',
    '<!-- Generated by tools/docs/generate-commands.mjs from messages/*.md. Do not edit. -->',
    '',
    escapeProse(command.summary ?? ''),
    '',
    '```bash',
    usageOf(id, flags),
    '```',
    '',
    ...(command.description ? ['## Description', '', escapeProse(command.description), ''] : []),
    ...(flags.length > 0 ? ['## Flags', '', ...flags.map(renderFlag)] : []),
    '### Global flags',
    '',
    '`--json` returns the result as JSON, `--flags-dir` reads flag values from a folder.',
    `The JSON format is pinned by [\`schemas/${schemaOf(id)}\`](${repoUrl}/blob/main/schemas/${schemaOf(id)}).`,
    '',
    ...(command.examples?.length
      ? ['## Examples', '', command.examples.map((example) => renderExample(id, example)).join('\n\n'), '']
      : []),
    `Source: [\`${source}\`](${repoUrl}/blob/main/${source})`,
    '',
  ].join('\n');
};

rmSync(outputDir, { recursive: true, force: true });
mkdirSync(outputDir, { recursive: true });
const ids = Object.keys(manifest.commands).sort(
  (a, b) => (ORDER.indexOf(a) === -1 ? 99 : ORDER.indexOf(a)) - (ORDER.indexOf(b) === -1 ? 99 : ORDER.indexOf(b))
);
for (const [index, id] of ids.entries()) {
  writeFileSync(path.join(outputDir, `${slugOf(id)}.md`), renderCommand(id, manifest.commands[id], index + 1));
}

console.log(`${ids.length} command pages written to ${path.relative(root, outputDir)}`);
